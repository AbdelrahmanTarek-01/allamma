const seen = new Set<string>();
export const WORDS: WordEntry[] = PACK.flatMap(([cat, d, line]) =>
  line.split(' ').filter(Boolean).map((w) => ({ w: w.replace(/_/g, ' '), d, cat })).filter((e) => (seen.has(e.w) ? false : (seen.add(e.w), true)))
);

/** Arabic normalisation for the "clue may not be a board word" check: no diacritics, no leading «ال», unified letters, no spaces. */
export const normalizeWord = (s: string) =>
  s
    .replace(/[ً-ْـ]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/\s+/g, '')
    .toLowerCase()
    .replace(/^ال/, '');
